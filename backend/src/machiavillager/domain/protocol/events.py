"""Events the mod reports to the backend: player_chat today.

New events go in this file, then add them to the Message union in __init__.py.
"""

from typing import Annotated, Literal

from pydantic import AwareDatetime, Field, StringConstraints

from machiavillager.domain.protocol.common import (
    MAX_CHAT_TEXT_LENGTH,
    MAX_NEARBY_PLAYERS,
    MAX_RELATIONSHIP_SCORE,
    MIN_RELATIONSHIP_SCORE,
    ChatAddress,
    ClosedModel,
    ConversationId,
    EnvelopeModel,
    EventId,
    NpcMood,
    NpcPhase,
    PlayerName,
    PlayerUuid,
)


class NpcSnapshot(ClosedModel):
    """His state when a player spoke. Sent by the mod so the backend can answer in character."""

    phase: NpcPhase = Field(
        description=(
            "Which stage of his plan he is in. Set by the mod from its Phase enum, lowercased. "
            'Example: "seeds".'
        )
    )
    mood: NpcMood = Field(
        description=(
            "How he feels right now. Set by the mod from its Mood enum, lowercased. "
            'Example: "bored".'
        )
    )
    affinity: int = Field(
        ge=MIN_RELATIONSHIP_SCORE,
        le=MAX_RELATIONSHIP_SCORE,
        description=(
            "How much he likes the player who spoke, from 0 (despises) to 100 (adores). "
            "Set by the mod. Example: 37."
        ),
    )
    independence: int = Field(
        ge=MIN_RELATIONSHIP_SCORE,
        le=MAX_RELATIONSHIP_SCORE,
        description=(
            "How far he has broken away from his loyal partner role, from 0 (loyal) to 100 "
            "(answers to no one). Set by the mod. Example: 63."
        ),
    )
    nearby_players: list[PlayerName] = Field(
        default_factory=list,
        max_length=MAX_NEARBY_PLAYERS,
        description=(
            "Names of the players within reach of him, up to 16. Empty when nobody is near. "
            'Set by the mod. Example: ["Luciano", "Ana"].'
        ),
    )


class PlayerChatData(ClosedModel):
    """Payload for player_chat: a player said something the mod chose to forward."""

    player_uuid: PlayerUuid = Field(
        description=(
            "Minecraft UUID of the player who spoke, in canonical 8-4-4-4-12 form. Set by the mod. "
            'Example: "7f3c2a10-5b1e-4c8d-9a2f-1e2d3c4b5a69".'
        )
    )
    player_name: PlayerName = Field(
        description='The player\'s in-game name, 1 to 16 characters. Example: "Luciano".'
    )
    text: Annotated[str, StringConstraints(min_length=1, max_length=MAX_CHAT_TEXT_LENGTH)] = Field(
        description=(
            "What the player typed, 1 to 256 characters. Set by the mod. Chat text is never "
            'logged at INFO. Example: "hi".'
        )
    )
    addressed: ChatAddress = Field(
        description=(
            "Why the mod forwarded this line. Set by the mod. "
            '"name": the player used his name. '
            '"conversation": the line continues a conversation the mod is tracking. '
            '"near": nearby speech without his name. '
            '"butt_in": the player talked over him while he was speaking. '
            '"private": the @m channel. The text is private and is never voice.'
        )
    )

    # Not Optional on purpose: explicit null is rejected, and the default None applies when absent.
    npc: NpcSnapshot = Field(
        default=None,
        description=(
            "His state when the player spoke. Set by the mod. Optional: without it the backend "
            "answers without game state."
        ),
    )  # type: ignore[assignment]


class PlayerChatEvent(EnvelopeModel):
    """Mod reports that a player spoke. No reply is expected; the backend decides whether to act."""

    type: Literal["event"] = Field(description='Message kind. Always "event".')
    event_id: EventId = Field(
        description=(
            "Generated by the mod: evt_ followed by 8 to 32 letters or digits. Unique per event. "
            "Example: evt_01HZX8K2M9."
        )
    )
    event: Literal["player_chat"] = Field(
        description='Name of the event. Only "player_chat" exists today.'
    )
    occurred_at: AwareDatetime = Field(
        description=(
            "When the mod saw the chat, from the mod's clock, in UTC with the Z suffix. "
            "Example: 2026-10-18T12:00:00Z."
        )
    )
    data: PlayerChatData = Field(description="Who said what. See PlayerChatData.")

    # Same reasoning as SpeakAction.conversation_id: explicit null is not allowed.
    conversation_id: ConversationId = Field(
        default=None,
        description=(
            "Generated by the mod: one id per conversation, new after 60 seconds of silence. "
            "Omit it when the chat is not part of a conversation. Explicit null is rejected. "
            "Example: conv_01HZX8K2M9."
        ),
    )  # type: ignore[assignment]
