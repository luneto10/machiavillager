"""Actions the backend asks the mod to run: speak and suggest_relationship.

New actions go in this file, then add them to BackendAction below and to the Message union in
__init__.py.
"""

from typing import Annotated, Literal

from pydantic import Field, model_validator

from machiavillager.domain.protocol.common import (
    MAX_AFFINITY_DELTA,
    MAX_FEELING_REASON_LENGTH,
    MAX_LATENCY_MS,
    MAX_SPEAK_LINES,
    MAX_TIMEOUT_MS,
    MIN_AFFINITY_DELTA,
    MIN_TIMEOUT_MS,
    ActionId,
    ClosedModel,
    ConversationId,
    EnvelopeModel,
    EventId,
    ModelName,
    PlayerUuid,
    SpeakLine,
)


class SpeakArgs(ClosedModel):
    """Arguments for speak: between 1 and 8 lines, each between 1 and 256 characters.

    Without "to", the lines are normal proximity speech. With "to", the lines are private text
    for one player. The mod paces the lines itself.
    """

    lines: Annotated[list[SpeakLine], Field(min_length=1, max_length=MAX_SPEAK_LINES)] = Field(
        description=(
            "What he says, in order. The mod paces the lines itself. Between 1 and 8 lines, each "
            'between 1 and 256 characters. Example: ["Hello, traveller."].'
        )
    )

    # Not Optional on purpose: an explicit null must be rejected, and the default None still
    # applies when the key is absent.
    to: PlayerUuid = Field(
        default=None,
        description=(
            "Private recipient. Set only for speech meant for one player: the lines reach that "
            "player alone, at any distance, and are never spoken aloud. Omit it for normal "
            "speech nearby. Explicit null is rejected. "
            'Example: "7f3c2a10-5b1e-4c8d-9a2f-1e2d3c4b5a69".'
        ),
    )  # type: ignore[assignment]


class SpeakAction(EnvelopeModel):
    """Backend asks the mod to speak a short sequence of lines as one action."""

    type: Literal["action"] = Field(description='Message kind. Always "action".')
    request_id: ActionId = Field(
        description=(
            "Generated by the backend: act_ followed by 16 random hex characters. Unique per "
            "action; every action_status for this action echoes it. "
            "Example: act_3fa9c01b7e2d4f60."
        )
    )
    action: Literal["speak"] = Field(
        description='Name of the allowlisted action. Only "speak" exists today.'
    )
    args: SpeakArgs = Field(description="Arguments for speak. See SpeakArgs.")
    timeout_ms: Annotated[int, Field(ge=MIN_TIMEOUT_MS, le=MAX_TIMEOUT_MS)] = Field(
        description=(
            "How long the mod may take before the action is reported as failed with reason "
            "timeout, in milliseconds. Between 100 and 120000. Example: 30000."
        )
    )

    # Not Optional on purpose: an explicit null must be rejected, and the default None still
    # applies when the key is absent.
    conversation_id: ConversationId = Field(
        default=None,
        description=(
            "Groups this speech with a conversation that the mod is tracking. Generated by the "
            "mod, see PlayerChatEvent. Omit it when the speech is not part of one. Explicit null "
            "is rejected."
        ),
    )  # type: ignore[assignment]

    # Same reasoning as conversation_id: explicit null is refused, absence means "not a reply".
    in_reply_to: EventId = Field(
        default=None,
        description=(
            "The player_chat event this speech answers. Set it only for a reply, so the mod does "
            "not count the speech as unprompted: replies skip the unprompted-speech cooldown. "
            "Omit it for speech the backend starts on its own. Explicit null is rejected. "
            "Example: evt_01HZX8K2M9."
        ),
    )  # type: ignore[assignment]

    # Dev info only, optional. Same rule as the fields above: explicit null is refused.
    model: ModelName = Field(
        default=None,
        description=(
            "Dev info: the model that wrote the lines, as provider:model, e.g. "
            "groq:qwen/qwen3.8-27b. The mod may show it. Omitted when no model wrote them, for "
            "example a canned line. Explicit null is rejected."
        ),
    )  # type: ignore[assignment]

    # Dev info only: how long the model took, so the dev HUD can show speed. Explicit null refused.
    latency_ms: Annotated[int, Field(ge=0, le=MAX_LATENCY_MS)] = Field(
        default=None,
        description=(
            "Dev info: how long the model took to answer, in milliseconds. Set together with "
            "model. Omitted when no model wrote the lines. Explicit null is rejected. Example: 480."
        ),
    )  # type: ignore[assignment]


class SuggestRelationshipArgs(ClosedModel):
    """Arguments for suggest_relationship: one player, a bounded change, and the reason for it."""

    player: PlayerUuid = Field(
        description=(
            "The player who spoke, in canonical 8-4-4-4-12 form. Set by the backend from the "
            'player_chat event it answers. Example: "7f3c2a10-5b1e-4c8d-9a2f-1e2d3c4b5a69".'
        )
    )
    affinity_delta: int = Field(
        ge=MIN_AFFINITY_DELTA,
        le=MAX_AFFINITY_DELTA,
        description=(
            "How much his affinity for this player moves, from -10 to 10. Negative when the player "
            "threatened, humiliated or betrayed him; positive when the player earned his trust. "
            "0 means no change and is never sent. Example: -6."
        ),
    )
    reason: str = Field(
        min_length=1,
        max_length=MAX_FEELING_REASON_LENGTH,
        description=(
            "What the player did, in a few words, 1 to 120 characters. Logged with the change; "
            'never shown to players. Example: "threatened him for real".'
        ),
    )

    @model_validator(mode="after")
    def _delta_is_not_zero(self) -> "SuggestRelationshipArgs":
        # JSON Schema cannot say "not 0" cleanly, so this rule lives in the model only.
        if self.affinity_delta == 0:
            raise ValueError("affinity_delta must not be 0; send no suggestion instead")
        return self


class SuggestRelationshipAction(EnvelopeModel):
    """Backend suggests a bounded change to how he feels about one player. The mod validates it."""

    type: Literal["action"] = Field(description='Message kind. Always "action".')
    request_id: ActionId = Field(
        description=(
            "Generated by the backend: act_ followed by 16 random hex characters. Unique per "
            "action; every action_status for this action echoes it. "
            "Example: act_3fa9c01b7e2d4f60."
        )
    )
    action: Literal["suggest_relationship"] = Field(
        description=(
            'Name of the allowlisted action. "suggest_relationship" suggests a feeling change; '
            "the mod validates, caps and applies it."
        )
    )
    args: SuggestRelationshipArgs = Field(
        description="Arguments for suggest_relationship. See SuggestRelationshipArgs."
    )
    timeout_ms: Annotated[int, Field(ge=MIN_TIMEOUT_MS, le=MAX_TIMEOUT_MS)] = Field(
        description=(
            "How long the mod may take before the action is reported as failed with reason "
            "timeout, in milliseconds. Between 100 and 120000. Example: 30000."
        )
    )

    # Same rule as SpeakAction.in_reply_to: explicit null is refused, absence means "not a reply".
    in_reply_to: EventId = Field(
        default=None,
        description=(
            "The player_chat event this suggestion comes from. Always set for this action. "
            "Explicit null is rejected. Example: evt_01HZX8K2M9."
        ),
    )  # type: ignore[assignment]


# Every action the backend can send, told apart by the action name.
BackendAction = Annotated[SpeakAction | SuggestRelationshipAction, Field(discriminator="action")]
