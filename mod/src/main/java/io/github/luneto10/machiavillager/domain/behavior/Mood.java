package io.github.luneto10.machiavillager.domain.behavior;

/** The NPC's current temperament. It shifts how the NPC weighs its possible actions. */
public enum Mood {
    /** Relaxed and sociable. */
    CALM,
    /** Restless, looking for something to do. */
    BORED,
    /** Annoyed, more likely to speak up. */
    IRRITATED
}
