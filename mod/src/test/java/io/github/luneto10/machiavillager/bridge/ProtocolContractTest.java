package io.github.luneto10.machiavillager.bridge;

import static org.junit.jupiter.api.Assertions.assertDoesNotThrow;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.Arguments;
import org.junit.jupiter.params.provider.MethodSource;

/**
 * Checks the mod against the generated contract: every valid example and every invalid case goes through the same
 * schema and decoder the game uses. The examples and the schema are generated by the backend, never edited here.
 */
class ProtocolContractTest {
    private static final Path SHARED_SCHEMA = Path.of("shared", "protocol.schema.json");
    private static final Path VALID_RELATIVE = Path.of("shared", "examples", "valid");
    // One JSON object per line: {"name": ..., "message": {...}}. The backend writes it; Java only reads it.
    private static final Path INVALID_JSONL = Path.of("shared", "examples", "invalid.jsonl");

    // Loaded once, the same validator the bridge uses at runtime.
    private static final SchemaValidator SCHEMA = new SchemaValidator();

    @Test
    void bundledSchema_isTheSharedGeneratedFile() throws IOException {
        // The build copies the file; a stale or hand-edited copy would make the mod check different rules.
        String bundled = readBundledSchema();

        assertEquals(Files.readString(repoRoot().resolve(SHARED_SCHEMA)), bundled);
    }

    @Test
    void examples_areNotEmpty() {
        // An empty folder or file would make the parameterized tests pass without checking anything.
        assertFalse(validExamples().isEmpty());
        assertFalse(invalidCases().isEmpty());
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("validExamples")
    void validExample_passesSchema(Path example) throws IOException {
        List<String> errors = SCHEMA.errors(Files.readString(example));

        assertTrue(errors.isEmpty(), () -> example.getFileName() + " should be valid: " + errors);
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("validExamples")
    void validExample_decodesWithoutError(Path example) throws IOException {
        String json = Files.readString(example);

        assertDoesNotThrow(() -> MessageCodec.decode(json), example.getFileName().toString());
    }

    // The Java side must also write what the schema accepts: decode, encode, then validate the output.
    @ParameterizedTest(name = "{0}")
    @MethodSource("validExamples")
    void validExample_encodeRoundTripValidatesSchema(Path example) throws IOException {
        String encoded = MessageCodec.encode(MessageCodec.decode(Files.readString(example)));

        List<String> errors = SCHEMA.errors(encoded);

        assertTrue(errors.isEmpty(), () -> example.getFileName() + " re-encoded invalid: " + errors);
    }

    // Each case is named <Model>.<field>.<rule>, so a failure names the message type and the broken rule.
    @ParameterizedTest(name = "{0}")
    @MethodSource("invalidCases")
    void invalidCase_failsSchema(String name, String message) {
        List<String> errors = SCHEMA.errors(message);

        assertFalse(errors.isEmpty(), () -> name + " should be rejected");
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("invalidCases")
    void invalidCase_isRejectedByDecoder(String name, String message) {
        assertThrows(MessageCodec.DecodeException.class, () -> MessageCodec.decode(message),
                name + " should be rejected");
    }

    static List<Path> validExamples() {
        return examplesIn(VALID_RELATIVE);
    }

    static List<Arguments> invalidCases() {
        Path file = repoRoot().resolve(INVALID_JSONL);
        try {
            // readAllLines accepts both \n and \r\n, so the file is read the same way on Windows.
            return Files.readAllLines(file, StandardCharsets.UTF_8).stream()
                    .map(ProtocolContractTest::toCase)
                    .toList();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    // The message is serialized again so the codec and the schema get the text the backend wrote, not a Java copy.
    private static Arguments toCase(String line) {
        JsonObject record = JsonParser.parseString(line).getAsJsonObject();
        return Arguments.of(record.get("name").getAsString(), record.get("message").toString());
    }

    private static String readBundledSchema() throws IOException {
        try (InputStream stream = ProtocolContractTest.class.getResourceAsStream(SchemaValidator.SCHEMA_RESOURCE)) {
            assertTrue(stream != null, "bundled schema missing from the classpath");
            return new String(stream.readAllBytes(), StandardCharsets.UTF_8);
        }
    }

    private static List<Path> examplesIn(Path relativeDir) {
        Path dir = repoRoot().resolve(relativeDir);
        try (var files = Files.list(dir)) {
            return files.filter(path -> path.toString().endsWith(".json")).sorted().toList();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    // Gradle runs tests from the mod/ folder; walk up so the lookup survives moving the module.
    private static Path repoRoot() {
        for (Path dir = Path.of("").toAbsolutePath(); dir != null; dir = dir.getParent()) {
            if (Files.exists(dir.resolve(SHARED_SCHEMA))) {
                return dir;
            }
        }
        throw new IllegalStateException("shared/protocol.schema.json not found above the working directory");
    }
}
